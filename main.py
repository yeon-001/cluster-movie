# --------------------------------------------------
# 묶음별 편 수 + 네 가지 속성 평균
# --------------------------------------------------

st.subheader("묶음별 요약")

summary = (
    cluster_df
    .groupby("묶음")
    .agg(
        편수=("movieNm", "size"),
        스크린_수_평균=("스크린 수", "mean"),
        누적_관객_평균=("누적 관객", "mean"),
        십위권_일수_평균=("10위권 일수", "mean"),
        롱런_지수_평균=("롱런 지수", "mean"),
    )
    .reindex(["㉮", "㉯", "㉰"])
    .reset_index()
)

summary.columns = [
    "묶음",
    "편 수",
    "스크린 수 평균",
    "누적 관객 평균",
    "10위권 일수 평균",
    "롱런 지수 평균",
]

st.dataframe(
    summary.style.format(
        {
            "편 수": "{:,.0f}편",
            "스크린 수 평균": "{:,.1f}",
            "누적 관객 평균": "{:,.1f}",
            "10위권 일수 평균": "{:,.1f}",
            "롱런 지수 평균": "{:,.2f}",
        }
    ),
    use_container_width=True,
    hide_index=True,
)
